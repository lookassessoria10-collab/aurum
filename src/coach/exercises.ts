const CASA: Env[] = ["casa"];
const ACADEMIA: Env[] = ["academia"];
const AMBOS: Env[] = ["casa", "academia"];

const knee = (rest: number, peak: number, side: Metric["side"] = "near"): Metric => ({ signal: "kneeFlex", side, rest, peak, label: "Flexão do joelho" });
const hip = (rest: number, peak: number, side: Metric["side"] = "near"): Metric => ({ signal: "hipFlex", side, rest, peak, label: "Flexão do quadril" });
const elbow = (rest: number, peak: number, side: Metric["side"] = "near"): Metric => ({ signal: "elbowFlex", side, rest, peak, label: "Flexão do cotovelo" });
const shoulder = (rest: number, peak: number, side: Metric["side"] = "near"): Metric => ({ signal: "shoulder", side, rest, peak, label: "Elevação do braço" });

const lateral = (label: string, metric: Metric, extra: Partial<Variant> = {}): Variant => ({ view: "lateral", label, metric, ...extra });
const frontal = (label: string, metric: Metric, extra: Partial<Variant> = {}): Variant => ({ view: "frontal", label, metric, ...extra });

const SAG = (signal = "bodyLine", above = 14): FormCheck => ({ signal, above, when: "any", ms: 400, cue: "Quadril caindo: contraia abdômen e glúteos" });
const PIKE = (signal = "bodyLine", below = -16): FormCheck => ({ signal, below, when: "any", ms: 400, cue: "Quadril alto demais: alinhe o corpo" });
const TRUNK_STILL = (above = 12, cue = "Tronco parado, sem balançar"): FormCheck => ({ signal: "trunkLean", drift: true, above, cue });
const KNEES_OUT: FormCheck = { signal: "kneeWidth", below: 0.78, when: "bottom", cue: "Joelhos para fora, na linha dos pés" };
const HEELS_DOWN: FormCheck = { signal: "heelRise", above: 0.42, when: "bottom", ms: 350, cue: "Calcanhares no chão" };
const CHEST_UP = (above = 52): FormCheck => ({ signal: "trunkLean", above, when: "bottom", cue: "Peito aberto: tronco mais ereto" });
const SIDE_TILT = (above = 12): FormCheck => ({ signal: "trunkLean", above, when: "any", ms: 400, cue: "Tronco reto, sem inclinar para o lado" });
const ELBOWS_TUCKED = (above = 35): FormCheck => ({ signal: "shoulder", above, cue: "Cotovelos parados, colados ao corpo" });
const SYMMETRY = (signal = "shoulderSym", above = 25): FormCheck => ({ signal, above, ms: 350, cue: "Suba os dois braços juntos" });

/** Agachamentos: de lado mede profundidade e tronco; de frente, os joelhos. */
const squatVariants = (opts: { peak?: number; chest?: number; frontPeak?: number } = {}): Variant[] => [
  lateral("De lado: profundidade e tronco", knee(15, opts.peak ?? 105), {
    checks: [CHEST_UP(opts.chest ?? 52), HEELS_DOWN],
    depthCue: "Desça mais, até a coxa ficar paralela ao chão",
  }),
  frontal(
    "De frente: alinhamento dos joelhos",
    { signal: "hipY", side: "near", rest: 0, peak: opts.frontPeak ?? 0.9, relative: true, label: "Descida do quadril" },
    { checks: [KNEES_OUT, SIDE_TILT(10)], depthCue: "Desça mais o quadril" },
  ),
];

