/** Onde posicionar o celular, conforme a vista e a posição do corpo. */
export function cameraTip(view: "frontal" | "lateral", posture: Exercise["posture"]) {
  const lado = view === "lateral" ? "de lado para você" : "de frente para você";
  switch (posture) {
    case "floor":
      return `Celular no chão, ${lado}, a uns 2 m. O corpo inteiro na horizontal precisa caber na tela.`;
    case "seated":
      return `Celular ${lado}, na altura do tronco. Ombros, braços e quadril precisam aparecer.`;
    case "bench":
      return `Celular ${lado}, na altura do banco, a uns 2 m. Ombros, braços e quadril na tela.`;
    case "hanging":
      return `Celular ${lado}, afastado o suficiente para mostrar as mãos na barra e o corpo.`;
    default:
      return `Celular ${lado}, na altura do quadril, a 2–3 m. Corpo inteiro na tela, da cabeça aos pés.`;
  }
}
